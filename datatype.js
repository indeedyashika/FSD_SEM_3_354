//datatypes in javascript
let a = 10; // number
console.log(typeof a); // number
let b = "Hello"; // string
console.log(typeof b); // string
let c = true; // boolean
console.log(typeof c); // boolean
let d = null; // null
console.log(typeof d); // object (this is a known bug in JavaScript, null is not an object)
let e; // undefined
console.log(typeof e); // undefined
let f = { name: "John", age: 30 }; // object
console.log(typeof f); // object 
let n;
console.log(typeof n); // undefined
let g = [1, 2, 3]; // array
console.log(typeof g); // object (arrays are technically objects in JavaScript)
const h = [1,2,3];
console.log(typeof h); //  array

